-- | Draws random cases once, from a fixed seed, and writes them to disk:
--
--   * src/Saved.hs: the cases, which from then on are a fixed sample;
--   * src/SavedAnswers.hs: their answers, which is all 'fromSaved' knows.
--
-- Run with: cabal run freeze
module Main (main) where

import Data.List (sort)
import Test.QuickCheck
import Test.QuickCheck.Gen (unGen)
import Test.QuickCheck.Random (mkQCGen)

main :: IO ()
main = do
  let cases = unGen (vectorOf 50 (resize 10 (arbitrary :: Gen [Int]))) (mkQCGen 42) 10
  writeFile "src/Saved.hs" $ unlines $
    [ "-- | Generated by tools/Freeze.hs from seed 42. Do not edit by hand."
    , "-- Random cases, drawn once and saved: from here on, a fixed sample."
    , "module Saved (saved) where"
    , ""
    , "saved :: [[Int]]"
    , "saved ="
    ] ++ listLines (map show cases)
  writeFile "src/SavedAnswers.hs" $ unlines $
    [ "-- | Generated by tools/Freeze.hs. Do not edit by hand."
    , "-- The answer to each saved case, as a table."
    , "module SavedAnswers (answers) where"
    , ""
    , "answers :: [([Int], [Int])]"
    , "answers ="
    ] ++ listLines [show (c, sort c) | c <- cases]
  where
    listLines xs = zipWith (\sep x -> "  " ++ sep ++ " " ++ x) ("[" : repeat ",") xs ++ ["  ]"]
